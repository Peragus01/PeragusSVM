export function translateHome(locale: HomeLocale, text: string): string {
  return locale === "en" ? text : (translations[locale][text] ?? text);
}

export const HomeLocaleContext = createContext<HomeLocale>("en");

export function useHomeTranslation() {
  const locale = useContext(HomeLocaleContext);
  return (text: string) => translateHome(locale, text);
}
